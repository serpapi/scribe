import { execSync, execFileSync } from "node:child_process";
import fs from 'node:fs';
import path from 'path';
import supportedLangs from './serpapi-transcript-languages.json' with { type: 'json' };
import { error } from "node:console";

/**
 * @typedef {Object} VideoSettings
 * @property {string} settings.serpApiKey The API key for SerpApi.
 * @property {string} settings.outputDir The absolute path to where the export file should be stored.
 * @property {string} settings.videoId The ID for the YouTube video.
 * @property {string} settings.videoUrl The full URL for the YouTube video.
 * @property {string} settings.videoCreator The channel name for the YouTube video.
 * @property {string} settings.videoTitle The title of the YouTube video.
 * @property {string} settings.videoDescription The description of the video.
 * @property {Array} settings.videoTags The video's tags.
 * @property {string} settings.videoLang The requested language of the video transcript. May not match the final output.
 * @property {boolean} settings.videoChaptersGenerated This is "true" if the video's chapters were automatically generated by YouTube.
 * @property {string} settings.videoDate The publish date of the YouTube video in YYY-MM-DD format.
 * @property {string} settings.outputFormat The output format for the file. Supported options are `markdown` and `txt`.
 */

// List of valid supported export options
export const outputFormats = ["markdown", "html", "epub", "txt", "rtf"];

// List of valid languages for SerpApi YouTube Video Transcript API
export const serpLangs = supportedLangs;

/**
 * Checks if a given command or executable is available to the system.
 * @param {string} command The name of the command to check.
 * @returns {boolean}
 */
export function checkCmdExists(command) {
    try {
        let checkCmd;
        // 'which' for Unix, 'where' for Windows
        if (process.platform === "win32") {
            checkCmd = `where ${command}`;
        } else {
            checkCmd = `which ${command}`
        }
        execSync(checkCmd, { stdio: 'ignore' });
        return true;
    } catch (e) {
        return false;
    }
}

/**
 * Removes the "Chapter X:" text from chapter titles. This is only needed until this SerpApi bug is fixed: https://github.com/serpapi/public-roadmap/issues/4629
 * @param {string} title A chapter title.
 * @returns {string} The cleaned chapter title.
 */
function cleanTitle(title) {
    return title.replace(/^(?:\s*Chapter\s+\d+\s*:\s*)+/i, '');
}

/**
 * Saves the book in the specified file format using Pandoc, and returns the absolute path to the file.
 * @param {VideoSettings} settings The video settings configuration. This reads the `setting.outputFormat` key.
 * @param {string} bookText The Markdown-formatted text for the book.
 * @returns {string} The absolute path to the file.
 */
export function saveFile(settings, bookText) {
    let outputFilePath;
    if (settings.outputFormat === "epub") {
        // ePub format
        // This adds a random UUID to prevent issues with Send to Kindle: https://www.amimetic.co.uk/blog/kindle-ready-ebooks-from-markdown
        outputFilePath = path.resolve(settings.outputDir, `${settings.videoTitle} ${settings.videoId}.epub`);
        execFileSync(
            "pandoc",
            ["-f", "markdown+yaml_metadata_block", "-t", "epub3", "--metadata", `uuid='${crypto.randomUUID()}'`, "--table-of-contents=true", "-o", outputFilePath],
            { input: bookText, encoding: 'utf8' }
        );
    } if (settings.outputFormat === "html") {
        // HTML format
        outputFilePath = path.resolve(settings.outputDir, `${settings.videoTitle} ${settings.videoId}.html`);
        execFileSync(
            "pandoc",
            ["-f", "markdown+yaml_metadata_block", "-t", "html", "--standalone", "--wrap=none", "--table-of-contents=true", "-o", outputFilePath],
            { input: bookText, encoding: 'utf8' }
        );
    } else if (settings.outputFormat === "txt") {
        // Plain text format
        outputFilePath = path.resolve(settings.outputDir, `${settings.videoTitle} ${settings.videoId}.txt`);
        execFileSync(
            "pandoc",
            ["-f", "markdown+yaml_metadata_block", "-t", "plain", "--wrap=none", "-o", outputFilePath],
            { input: bookText, encoding: 'utf8' }
        );
    } else if (settings.outputFormat === "rtf") {
        // Rich Text Format
        outputFilePath = path.resolve(settings.outputDir, `${settings.videoTitle} ${settings.videoId}.rtf`);
        execFileSync(
            "pandoc",
            ["-f", "markdown+yaml_metadata_block", "-t", "rtf", "--standalone", "--wrap=none", "-o", outputFilePath],
            { input: bookText, encoding: 'utf8' }
        );
    } else if (settings.outputFormat === "markdown") {
        // Markdown format, no conversion is needed
        outputFilePath = path.resolve(settings.outputDir, `${settings.videoTitle} ${settings.videoId}.md`);
        fs.writeFileSync(outputFilePath, bookText);
    }
    return outputFilePath;
}

/**
 * Check information for a SerpApi account.
 * More info: https://serpapi.com/account-api
 * @param {string} api_key The API key connected to the account
 * @returns {object} The JSON response from SerpApi.
 */
export async function getAccountInfo(apiKey) {
    // Create API request
    const url = `https://serpapi.com/account?api_key=${apiKey}`
    try {
        const response = await fetch(url);
        if (!response.ok) {
            throw new Error(`Response status: ${response.status}`);
        }
        const result = await response.json();
        return result;
    } catch (error) {
        throw new Error(error);
    }
}

/**
 * Get the URL, title, creator, and publish date of a YouTube video with SerpApi, and return them in a JSON object ready for appending to a VideoSettings object.
 * @param {string} videoId The ID of the YouTube video.
 * @param {string} serpApiKey The API key for SerpApi.
 * @param {string} langCode The language code to use for the search.
 * @returns {Promise<object>} The object with `videoUrl`, `videoTitle`, `videoCreator`, and `videoDate` keys.
 */
export async function getSerpVideoInfo(videoId, serpApiKey, langCode) {
    let result;
    // Send API request
    const apiReq = {
        engine: "youtube_video",
        v: videoId,
        api_key: serpApiKey,
        // Force English in US for a predictable date format
        gl: "us",
        hl: "en"
    };
    const url = "https://serpapi.com/search?" + new URLSearchParams(apiReq);
    try {
        const response = await fetch(url);
        if (!response.ok) {
            throw new Error(`Response status: ${response.status}`);
        }
        result = await response.json();
    } catch (error) {
        throw new Error(error);
    }
    // Convert date to Pandoc's preferred YYYY-MM-DD format
    let publishDate;
    if (result?.published_date) {
        const d = new Date(result.published_date + " UTC");
        publishDate = d.toISOString().slice(0, 10);
    }
    // Return data
    const data = {
        videoUrl: `https://www.youtube.com/watch?v=${videoId}`,
        videoTitle: (result?.title || "Unknown Title"),
        videoCreator: (result?.channel?.name || "Unknown Creator"),
        videoDate: (publishDate || ""),
        videoDescription: (result?.description?.content || ""),
        videoTags: (result?.keywords || []),
        videoChaptersGenerated: (result?.chapters?.[0]?.auto_generated === true)
    }
    return data;
}

/**
 * Get a YouTube video transcript with SerpApi and convert it to Pandoc's Markdown format.
 * @param {VideoSettings} settings The settings configuration.
 * @returns {Promise<string>} The generated book in Markdown format.
 */
export async function getSerpTranscript(settings) {
    let result;
    // Send API request
    const apiReq = {
        engine: "youtube_video_transcript",
        v: settings.videoId,
        // Supported languages: https://serpapi.com/youtube-video-transcript-languages
        language_code: settings.videoLang,
        api_key: settings.serpApiKey
    };
    const url = "https://serpapi.com/search?" + new URLSearchParams(apiReq);
    try {
        const response = await fetch(url);
        if (!response.ok) {
            throw new Error(`Response status: ${response.status}`);
        }
        result = await response.json();
    } catch (error) {
        throw new Error(error);
    }
    // Check that a transcript exists and there are no errors
    if (result?.error) {
        throw new Error(result.error);
    } else if (!result?.transcript) {
        throw new Error("Transcript is not available");
    }
    // Combine the chapters and snippets into one object
    // Don't use chapters if they were auto-generated by YouTube, because they're short and can interrupt sentences
    let chapters;
    const isSoundOnly = s => /^\s*(\[[^\]]*\]\s*)+$/.test(s);
    if (result?.chapters && !settings.videoChaptersGenerated) {
        chapters = result.chapters.map(c => ({ ...c, snippets: [] }));
    } else {
        chapters = [{ chapter: null, start_ms: 0, snippets: [] }]
    }
    let chapterIndex = 0;
    for (const line of result.transcript) {
        while (chapterIndex + 1 < chapters.length && chapters[chapterIndex + 1].start_ms <= line.start_ms) chapterIndex++;
        // Skip lines in the transcript that are only sounds, like "[upbeat music]" or "[laughing]"
        if (isSoundOnly(line.snippet)) continue;
        // Remove leading line dash from some lines
        const snippet = line.snippet.replace(/^\s*-\s*/, "");
        // Add the snippet
        chapters[chapterIndex].snippets.push({ ...line, snippet });
    }
    // Create Pandoc-formatted Markdown file, with metadata in YAML block at start
    // Documentation: https://pandoc.org/MANUAL.html#extension-yaml_metadata_block
    let bookText = `---
title: "${settings.videoTitle}"
author: "${settings.videoCreator}"
date: ${settings.videoDate}
keywords: [${settings.videoTags.toString()}]
---

**This file was converted with SerpApi Scribe: [https://github.com/serpapi/scribe](https://github.com/serpapi/scribe)**

**Link to video: [${settings.videoUrl}](${settings.videoUrl})**

`;
    for (let chapter of chapters) {
        // Add chapter title
        if (chapter?.chapter) {
            bookText += `# ${cleanTitle(chapter.chapter)}\n\n`;
        } else {
            bookText += "# Transcript\n\n";
        }
        // Add snippets from chapter
        for (let [i, value] of chapter.snippets.entries()) {
            bookText += value.snippet;
            // For every 10 snippets, add a linked timestamp
            if (i % 10 === 0) {
                let timestamp = value.start_ms / 1000;
                bookText += ` [[${value.start_time_text}](https://youtu.be/${settings.videoId}?t=${timestamp})]`;
            }
            bookText += "\n\n";
        }
    }
    // Add a chapter at the end for the video description
    if (settings.videoDescription) {
        bookText += `# Description\n\n${settings.videoDescription}`;
    }
    return bookText;
}